keys = [0x37, 0x12, 0x8a, 0x01, 0x55, 0x2f]
offs = [0x05, 0x11, 0x03, 0x22, 0x09, 0x14]
expected = [0xf9, 0x98, 0x76, 0x32, 0x25, 0x90, 0xcb, 0xbd, 0x5e, 0x4d, 0x50, 0x30, 0x73, 0x22,
            0xc3, 0xc9, 0xf7, 0x9b, 0xd3, 0xc4, 0x24, 0x70, 0x49, 0x1c, 0x5b]
IV = 0xA5

flag = ""
feedback = IV
for i, e in enumerate(expected):
    k = keys[i % len(keys)]
    o = offs[i % len(offs)]
    val = (e - o) & 0xFF
    val = val ^ k ^ feedback
    flag += chr(val)
    feedback = e

print(flag)
